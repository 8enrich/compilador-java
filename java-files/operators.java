public class Comparison {

    public static void test() {
        int a = 10;
        int b = 20;

        if (a == b) {
            a += 1;
        }

        if (a != b) {
            b -= 1;
        }

        if (a <= b) {
            a *= 2;
        }

        if (a >= b) {
            b /= 2;
        }

        return;
    }
}
